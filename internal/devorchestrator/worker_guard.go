// The guard layer is generated per spawn into the task's runtime dir: the
// canonical worker-guard.sh (embedded, drift-checked against
// .rddev.example/guard/worker-guard.sh), worker-settings.json (Claude Code
// permissions: dontAsk + deny list + the PreToolUse hook wiring) and
// run-worker.sh (the reaper wrapper that keeps the claude process alive past
// rddev's own exit and records its exit code).

