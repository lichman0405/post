// The guard layer is generated per spawn into the task's runtime dir: the
// canonical worker-guard.sh (embedded, drift-checked against
// .rddev.example/guard/worker-guard.sh), worker-settings.json (Claude Code
// permissions: dontAsk + deny list + the PreToolUse hook wiring) and
// run-worker.sh (the reaper wrapper that keeps the claude process alive past
// rddev's own exit and records its exit code).

//go:embed embed/worker-guard.sh
var guardScript string

// GuardScript returns the embedded canonical worker-guard.sh.
func GuardScript() string { return guardScript }

// GuardOpts parametrizes the generated guard files.
type GuardOpts struct {
	RepoRoot    string
	TaskID      string
	Worktree    string
	ResultDir   string
	DockerGrant bool
}

// denyRules is the blunt Claude Code permission layer (the hook is the
// precision layer, L1-20260912-9). Everything here is unconditionally
